const seeds = [42, 77, 99];
let mdContent = `# 🏙️ Realistic Town Life Simulation & Demographic Census Report

*Generated by Antigravity AI — Flock Town Simulation Engine*

---

## 📊 Overview

The **Flock Town Life Engine** provides deterministic, high-performance simulation of families, household structures, job role allocation, workplace capacities, and daily routines across rural towns.

---

`;

for (const seed of seeds) {
  const world = generateWorld(seed, 96, 96, { townType: "farm" });
  const census = getTownCensus(world);

  mdContent += `### 🏡 Town: **${census.townName}** (Seed \`${seed}\` — 96×96)

* **Total Population**: **${census.totalPopulation}** citizens across **${census.totalHouseholds}** households.
* **Labor Force**: **${census.employedCount}** Employed / **${census.unemployedCount}** Unemployed (**${census.employmentRate}% Employment Rate**).
* **Demographic Breakdown**: **${census.neutralCount}** Neutral Citizens, **${census.believerCount}** Believers, **${census.apostateCount}** Apostates.

#### 🛠️ Industry Sector Employment
* 🏛️ **Civic & Public Safety**: **${census.sectorCounts.civic}** workers (Sheriff, Fire Dept, Post Office, Schools)
* 🛒 **Retail & Services**: **${census.sectorCounts.services}** workers (Gas Station, Diner, Supermarket, Bank)
* 🏭 **Industry & Freight**: **${census.sectorCounts.industry}** workers (Factory, Warehouse, Rail Depot, Grain Elevator)
* 🚜 **Agriculture**: **${census.sectorCounts.agriculture}** workers (Farmland, Barns, Silos, Orchards)

#### 👨‍👩‍👧‍👦 Sample Family Household Cards

`;

  // Sample 4 populated household lots
  let sampled = 0;
  for (let t = 0; t < world.terrain.length && sampled < 4; t++) {
    if (world.pop[t] >= 3) {
      const hh = getHouseholdInfo(world, t);
      if (!hh) continue;
      sampled++;

      mdContent += `##### 🏠 **${hh.surname} Family** (Parcel \`[${hh.x}, ${hh.y}]\` — ${hh.size} Family Members)
* **Status**: \`${hh.employmentStatus.toUpperCase()}\` | **Daily Household Income**: **$${hh.dailyIncome}/day** | **Dissent**: **${(hh.dissent * 100).toFixed(1)}%**
* **Family Roster**:
`;
      for (const m of hh.members) {
        if (m.job) {
          mdContent += `  * 👤 **${m.name}** (Age ${m.age}, *${m.role}*): **${m.job.title}** @ Workplace Tile \`#${m.workplaceTile}\` ($${m.job.wage}/day)\n`;
        } else {
          mdContent += `  * 👤 **${m.name}** (Age ${m.age}, *${m.role}*): *Unemployed / Dependent*\n`;
        }
      }
      mdContent += `\n`;
    }
  }

  // Render visual snapshot of map
  const balance = loadBalance(JSON.parse(fs.readFileSync(new URL("../balance.json", import.meta.url))));
  const sim = createSim({ seed, balance, world, spawns: [{ id: 1, archetype: "dawn" }] });
  const res = renderTown(sim, { width: 768, height: 768, scale: 1 });
  const buffer = Buffer.from(res.data.buffer, res.data.byteOffset, res.data.byteLength);
  const pngPathArtifact = path.join(artifactsDir, `town_simulation_seed${seed}.png`);
  const pngPathGallery = path.join(galleryDir, `town_simulation_seed${seed}.png`);

  writePNG(pngPathArtifact, 768, 768, buffer);
  writePNG(pngPathGallery, 768, 768, buffer);

  mdContent += `![Town Life Map Seed ${seed}](file:///${pngPathArtifact.replace(/\\/g, "/")})\n\n---\n\n`;
}

const mdPathArtifact = path.join(artifactsDir, `town_simulation.md`);
fs.writeFileSync(mdPathArtifact, mdContent);

console.log(`Town Simulation Census QA complete! Artifact saved to ${mdPathArtifact}`);
