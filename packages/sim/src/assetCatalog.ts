/** Quick lookup for asset animation modes. */
export const ASSET_ANIMATION_MAP = new Map<string, AnimationMode>(
  MASTER_ASSET_CATALOG.map((a) => [a.id, a.animMode])
);

/** Helper to check whether an asset is animated. */
export function isAssetAnimated(id: string): boolean {
  const mode = ASSET_ANIMATION_MAP.get(id);
  return mode !== undefined && mode !== "STATIC";
}
